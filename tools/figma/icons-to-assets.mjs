#!/usr/bin/env node
// tools/figma/out/icons.json(Figma SVG) → PADODesignSystem 에셋 카탈로그 + PADOIcon.generated.swift
// 단색 아이콘은 template(색을 코드에서 입힘), 서비스 로고(Spotify 등)는 원본 색 그대로.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const pkg = path.join(root, 'Packages/PADODesignSystem/Sources/PADODesignSystem');
const icons = JSON.parse(fs.readFileSync(path.join(root, 'tools/figma/out/icons.json'), 'utf8'));
const BRAND = new Set(['spotify', 'appleMusic', 'youtubeMusic']);
const catalog = path.join(pkg, 'Resources/Icons.xcassets');
fs.rmSync(catalog, { recursive: true, force: true });
fs.mkdirSync(catalog, { recursive: true });
fs.writeFileSync(path.join(catalog, 'Contents.json'), JSON.stringify({ info: { author: 'xcode', version: 1 } }, null, 2) + '\n');
for (const [name, svg] of Object.entries(icons)) {
  const dir = path.join(catalog, `${name}.imageset`);
  fs.mkdirSync(dir);
  fs.writeFileSync(path.join(dir, `${name}.svg`), svg);
  fs.writeFileSync(path.join(dir, 'Contents.json'), JSON.stringify({
    images: [{ filename: `${name}.svg`, idiom: 'universal' }],
    info: { author: 'xcode', version: 1 },
    properties: { 'preserves-vector-representation': true, 'template-rendering-intent': BRAND.has(name) ? 'original' : 'template' },
  }, null, 2) + '\n');
}
const names = Object.keys(icons);
const swift = [
  '// Generated by tools/figma/icons-to-assets.mjs from Figma (PADO › MVP › Icon/*, Service/*) — 직접 고치지 마세요.',
  'import SwiftUI', '',
  'public enum PADOIcon: String, CaseIterable, Sendable {',
  ...names.map(n => `  case ${n}`),
  '', '  /// 서비스 로고는 원본 색, 나머지는 foregroundStyle로 색을 입힌다',
  `  public var isBrand: Bool { [${[...BRAND].map(n => '.' + n).join(', ')}].contains(self) }`,
  '', '  public var image: Image { Image(rawValue, bundle: .module) }',
  '}', '',
].join('\n');
fs.writeFileSync(path.join(pkg, 'Icons/PADOIcon.generated.swift'), swift);
console.log(`[icons] ${names.length}개 → Resources/Icons.xcassets, Icons/PADOIcon.generated.swift`);
