// 디자인 토큰 변환 — Figma 변수 원본(figma-variables.json) → 정리된 토큰 → 플랫폼별 코드.
// 순수 함수만 둔다 (파일 입출력은 build.mjs). 테스트: tools/tokens/lib.test.mjs

export const DEFAULT_MODE = 'J · 스카이 퓨어';

/** "color/card-2" → "card2", "text/Body Strong" → "bodyStrong" */
export function camel(name) {
  const last = name.split('/').pop();
  const words = last.split(/[\s-]+/).filter(Boolean);
  return words.map((w, i) => (i === 0 ? w.toLowerCase() : w[0].toUpperCase() + w.slice(1).toLowerCase())).join('');
}

/** Figma 글꼴 스타일 이름 → CSS 굵기 */
const WEIGHTS = { Thin: 100, ExtraLight: 200, Light: 300, Regular: 400, Medium: 500, SemiBold: 600, Bold: 700, ExtraBold: 800, Black: 900 };
export function weightOf(style) {
  const w = WEIGHTS[style.replace(/\s+/g, '')];
  if (!w) throw new Error(`알 수 없는 글꼴 스타일: ${style}`);
  return w;
}

/** "#RRGGBB" 또는 "#RRGGBBAA" → { r, g, b, a } (0~1) */
export function parseHex(hex) {
  const m = /^#([0-9a-f]{6})([0-9a-f]{2})?$/i.exec(hex);
  if (!m) throw new Error(`색 형식이 아님: ${hex}`);
  const n = parseInt(m[1], 16);
  return { r: (n >> 16 & 255) / 255, g: (n >> 8 & 255) / 255, b: (n & 255) / 255, a: m[2] ? parseInt(m[2], 16) / 255 : 1 };
}

/** Figma 자간(퍼센트는 글자 크기 기준) → 포인트. iOS kerning·CSS letter-spacing 모두 px/pt 단위 */
export function letterSpacingPt(ls, fontSize) {
  if (!ls || ls.value === 0) return 0;
  const v = ls.unit === 'PERCENT' ? (fontSize * ls.value) / 100 : ls.value;
  return Math.round(v * 100) / 100;
}

/** Figma 줄 높이 → 포인트 (AUTO는 null — 글꼴 기본 줄 높이를 쓴다) */
export function lineHeightPt(lh, fontSize) {
  if (!lh || lh.unit === 'AUTO') return null;
  return lh.unit === 'PERCENT' ? Math.round(fontSize * lh.value) / 100 : lh.value;
}

/**
 * Figma 원본 → 정리된 토큰 (W3C Design Tokens 형식에 가깝게).
 * codeOnly: Figma에 아직 없는 토큰(간격 등). 디자이너가 Figma 변수로 옮기면 거기서 지운다.
 */
export function normalize(raw, { mode = DEFAULT_MODE, codeOnly = {} } = {}) {
  const col = raw.collections.find(c => c.name === 'PADO Theme');
  if (!col) throw new Error('"PADO Theme" 컬렉션이 없음');
  if (!col.modes.includes(mode)) throw new Error(`모드 "${mode}" 없음 (있는 모드: ${col.modes.join(', ')})`);
  const out = { $meta: { source: raw.source, mode }, color: {}, radius: {}, spacing: {}, typography: {} };
  for (const v of col.variables) {
    const value = v.values[mode];
    if (value && typeof value === 'object' && 'alias' in value) throw new Error(`별칭 변수는 아직 지원하지 않음: ${v.name}`);
    const [group] = v.name.split('/');
    if (v.type === 'COLOR' && group === 'color') out.color[camel(v.name)] = { $type: 'color', $value: value };
    else if (v.type === 'FLOAT' && group === 'radius') out.radius[camel(v.name)] = { $type: 'dimension', $value: value };
  }
  for (const s of raw.textStyles) {
    if (!s.name.startsWith('text/')) continue;
    out.typography[camel(s.name)] = {
      $type: 'typography',
      $value: {
        fontFamily: s.fontFamily,
        fontWeight: weightOf(s.fontStyle),
        fontSize: s.fontSize,
        lineHeight: lineHeightPt(s.lineHeight, s.fontSize),
        letterSpacing: letterSpacingPt(s.letterSpacing, s.fontSize),
      },
    };
  }
  for (const [k, v] of Object.entries(codeOnly.spacing ?? {})) out.spacing[k] = { $type: 'dimension', $value: v, $extensions: { 'pado.codeOnly': true } };
  return out;
}

const HEADER = 'Generated by tools/tokens/build.mjs from tokens/figma-variables.json — 직접 고치지 말고 `npm run tokens` 로 다시 만드세요.';
const num = n => (Number.isInteger(n) ? String(n) : String(Math.round(n * 1000) / 1000));

export function toSwift(t) {
  const lines = [`// ${HEADER}`, `// Figma 모드: ${t.$meta.mode}`, 'import SwiftUI', '', 'public enum PADOTokens {'];
  lines.push('  public enum Color {');
  for (const [k, v] of Object.entries(t.color)) {
    const { r, g, b, a } = parseHex(v.$value);
    lines.push(`    /// ${v.$value}`);
    lines.push(`    public static let ${k} = SwiftUI.Color(.sRGB, red: ${num(r)}, green: ${num(g)}, blue: ${num(b)}, opacity: ${num(a)})`);
  }
  lines.push('  }', '', '  public enum Radius {');
  for (const [k, v] of Object.entries(t.radius)) lines.push(`    public static let ${k}: CGFloat = ${num(v.$value)}`);
  lines.push('  }', '', '  /// 간격 — Figma 변수에 아직 없어 코드에서 정한 4pt 단위 값 (Figma로 옮기면 생성 원본이 바뀐다)', '  public enum Spacing {');
  for (const [k, v] of Object.entries(t.spacing)) lines.push(`    public static let ${k}: CGFloat = ${num(v.$value)}`);
  lines.push('  }', '', '  public enum Typography {');
  for (const [k, v] of Object.entries(t.typography)) {
    const x = v.$value;
    lines.push(`    public static let ${k} = PADOTextStyle(name: "${k}", family: "${x.fontFamily}", weight: ${x.fontWeight}, size: ${num(x.fontSize)}, lineHeight: ${x.lineHeight == null ? 'nil' : num(x.lineHeight)}, letterSpacing: ${num(x.letterSpacing)})`);
  }
  lines.push('  }', '', '  /// 미리보기 카탈로그·테스트용 목록', '  public static let colorNames: [(name: String, hex: String)] = [');
  for (const [k, v] of Object.entries(t.color)) lines.push(`    ("${k}", "${v.$value}"),`);
  lines.push('  ]', '', '  public static let textStyles: [PADOTextStyle] = [');
  for (const k of Object.keys(t.typography)) lines.push(`    Typography.${k},`);
  lines.push('  ]', '}', '');
  return lines.join('\n');
}

export function toTypeScript(t) {
  const obj = group => Object.fromEntries(Object.entries(t[group]).map(([k, v]) => [k, v.$value]));
  return [
    `// ${HEADER}`,
    `// Figma 모드: ${t.$meta.mode}`,
    `export const colors = ${JSON.stringify(obj('color'), null, 2)} as const;`,
    '',
    `export const radius = ${JSON.stringify(obj('radius'), null, 2)} as const;`,
    '',
    `export const spacing = ${JSON.stringify(obj('spacing'), null, 2)} as const;`,
    '',
    `export const typography = ${JSON.stringify(obj('typography'), null, 2)} as const;`,
    '',
  ].join('\n');
}

const kebab = s => s.replace(/[A-Z0-9]/g, m => '-' + m.toLowerCase());
export function toCss(t) {
  const lines = [`/* ${HEADER} */`, `/* Figma 모드: ${t.$meta.mode} */`, ':root {'];
  for (const [k, v] of Object.entries(t.color)) lines.push(`  --pado-color${kebab(k).replace(/^(?!-)/, '-')}: ${v.$value};`);
  for (const [k, v] of Object.entries(t.radius)) lines.push(`  --pado-radius-${kebab(k)}: ${v.$value}px;`);
  for (const [k, v] of Object.entries(t.spacing)) lines.push(`  --pado-space-${kebab(k)}: ${v.$value}px;`);
  for (const [k, v] of Object.entries(t.typography)) {
    const x = v.$value, n = kebab(k);
    lines.push(`  --pado-text-${n}: ${x.fontWeight} ${x.fontSize}px/${x.lineHeight == null ? 'normal' : x.lineHeight + 'px'} "${x.fontFamily}", sans-serif;`);
    if (x.letterSpacing) lines.push(`  --pado-text-${n}-tracking: ${x.letterSpacing}px;`);
  }
  lines.push('}', '');
  return lines.join('\n');
}

/**
 * 다른 코드베이스의 색 정의와 비교 — "key: '#RRGGBB'" 꼴을 찾아 이름이 같은 토큰과 값을 견준다.
 * 반환: [{ key, token, other }] (값이 다른 것만), 그리고 상대에만 있는 키 목록
 */
export function colorDrift(t, sourceText) {
  const found = {};
  for (const m of sourceText.matchAll(/\b([A-Za-z][A-Za-z0-9]*)\s*:\s*['"](#[0-9a-fA-F]{6})['"]/g)) found[m[1]] = m[2].toUpperCase();
  const diffs = [], onlyOther = [];
  for (const [k, hex] of Object.entries(found)) {
    if (!t.color[k]) { onlyOther.push(k); continue; }
    if (t.color[k].$value.toUpperCase() !== hex) diffs.push({ key: k, token: t.color[k].$value, other: hex });
  }
  return { diffs, onlyOther };
}
